import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { captureElectron } from './capture-electron.mjs';
const require = createRequire(import.meta.url);
const { _electron } = require(process.env.KX_PLAYWRIGHT_PATH || 'playwright');
const root = process.cwd(), packaged = process.argv.includes('--packaged');
const version = JSON.parse(await fs.readFile('package.json', 'utf8')).version;
const label = packaged ? 'packaged' : 'source';
const executablePath = path.join(root, packaged ? `release/控小助-${version}-win32-x64/控小助.exe` : 'node_modules/electron/dist/electron.exe');
const dataDir = path.join(root, '.test-data', `audio-intro-${label}-${Date.now()}`);
const env = { ...process.env, KX_TEST_MODE: '1', KX_TEST_SHOW: '1', KX_TEST_DATA_DIR: dataDir };
delete env.ELECTRON_RUN_AS_NODE;
const report = { version, executablePath, dataDir, packaged, startedAt: new Date().toISOString(), checks: [], errors: [], scope: '实际 Electron、本地配乐输出电平与跨页面连续播放、入场模型与偏好持久化；独立数据，不调用在线模型。' };
const record = (name, detail = true) => { report.checks.push({ name, detail }); console.log('PASS', name); };
let app, page, home;
const rendererErrors = [], externalRequests = [], oldModels = [];
async function launch() {
  app = await _electron.launch({ executablePath, args: packaged ? [] : [root], env, timeout: 40000 });
  page = await app.firstWindow();
  page.on('pageerror', e => rendererErrors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) externalRequests.push(r.url()); if (/\.glb(?:$|[?#])/i.test(r.url())) oldModels.push(r.url()); });
  await page.getByTestId('homepage-frame').waitFor();
  home = await (await page.getByTestId('homepage-frame').elementHandle()).contentFrame();
  await home.waitForFunction(() => window.__kxHome?.getState().ready, null, { timeout: 60000 });
}
async function close() { await app.close(); app = null; }
const audio = () => page.evaluate(() => window.__kxAudio.getState());
const homeState = () => home.evaluate(() => window.__kxHome.getState());
async function completeIntro() { await home.waitForFunction(() => window.__kxHome.getState().intro.completed, null, { timeout: 30000 }); }
async function sounding() { await page.waitForFunction(() => window.__kxAudio?.getState().outputRms > 0.00001, null, { timeout: 30000 }); }
try {
  await fs.mkdir('evidence/screenshots', { recursive: true });
  await launch();
  await home.waitForFunction(() => { const s = window.__kxHome.getState(); return s.intro.active && s.intro.progress > 0.15 && s.intro.progress < 0.95; }, null, { timeout: 15000 });
  const opening = await homeState();
  assert.equal(opening.stats.sharedCartridgeGeometry, true);
  assert.ok(opening.stats.archivePartCount > 0);
  assert.equal(await home.locator('#boot, .boot-logo').count(), 0);
  await captureElectron(app, `evidence/screenshots/audio-${label}-intro.png`);
  record('入场中的整排模型与详情共享自研信号匣几何，无原品牌片头', { intro: opening.intro, parts: opening.stats.archivePartCount });
  await completeIntro();
  await sounding();
  const first = await audio();
  assert.equal(first.contextState, 'running'); assert.equal(first.musicStartCount, 1); assert.equal(first.sourceCount, 3);
  record('欢迎与阵列完成后开始本地三轨循环配乐', first);
  await home.locator('[data-action="open"]').first().click();
  await home.waitForFunction(() => window.__kxHome.getState().stats.signal.phase === 'clear', null, { timeout: 45000 });
  assert.ok((await audio()).playedKeys > 0);
  await captureElectron(app, `evidence/screenshots/audio-${label}-signal.png`);
  record('傅里叶解析与重新合成的文字声音触发');
  await home.getByTestId('home-start-motor').click();
  await page.getByTestId('run-simulation').waitFor();
  await sounding();
  const workspace = await audio();
  assert.equal(workspace.musicStartCount, first.musicStartCount);
  assert.equal(workspace.musicStartedAt, first.musicStartedAt);
  assert.equal(workspace.sourceCount, 3); assert.ok(workspace.currentTime > first.currentTime);
  assert.equal(await page.getByTestId('homepage-frame').isVisible(), false);
  record('主页进入实验台后同一音源和起播时间，仍有输出', workspace);
  // The hidden iframe cannot change settings or request sounds behind the workbench.
  await home.evaluate(() => parent.postMessage({ source: 'kongxiaozhu-home', type: 'audio-settings', patch: { enabled: false } }, '*'));
  await page.evaluate(() => window.postMessage({ source: 'kongxiaozhu-home', type: 'audio-settings', patch: { enabled: false } }, '*'));
  await page.waitForTimeout(150);
  assert.equal((await audio()).preferences.enabled, true);
  record('后台 frame 与其他窗口不能更改声音');
  await page.getByTestId('run-simulation').click();
  await page.waitForFunction(() => window.__kxAudio.getState().effectCount > 0);
  const loopWait = Math.ceil(Math.max(0, first.loopDuration - (workspace.currentTime - first.musicStartedAt)) * 1000 + 8000);
  await page.waitForFunction(() => { const s = window.__kxAudio.getState(); return s.completedLoops >= 1 && s.outputRms > 0.00001; }, null, { timeout: Math.min(60000, loopWait) });
  const looped = await audio();
  assert.equal(looped.musicStartCount, 1); assert.equal(looped.musicStartedAt, first.musicStartedAt);
  record('实际跨过完整循环边界，无重新创建音源且输出继续', looped);
  await page.getByTestId('open-settings').click();
  await page.getByLabel('文字解析音效', { exact: true }).uncheck();
  await page.getByLabel('配乐音量', { exact: true }).fill('17');
  await page.getByTestId('audio-master').click();
  await page.waitForFunction(() => { const s = window.__kxAudio.getState(); return !s.preferences.enabled && s.outputRms < 0.000001; });
  assert.equal((await audio()).musicStartCount, 1);
  await captureElectron(app, `evidence/screenshots/audio-${label}-settings.png`);
  record('总开关实际静音，音量与文字音偏好独立保存');
  await page.getByRole('button', { name: '关闭对话框', exact: true }).click();
  await page.getByTestId('feature-home').click();
  await page.getByTestId('homepage-frame').waitFor({ state: 'visible' });
  assert.equal((await homeState()).intro.completed, true);
  await home.locator('[data-action="settings"]').click();
  assert.equal(await home.locator('[data-audio-toggle="enabled"]').getAttribute('aria-pressed'), 'false');
  assert.equal(await home.locator('[data-audio-toggle="typing"]').getAttribute('aria-pressed'), 'false');
  assert.equal(await home.getByLabel('配乐音量', { exact: true }).inputValue(), '17');
  await home.locator('[data-audio-toggle="enabled"]').click();
  await sounding();
  assert.equal((await audio()).musicStartedAt, first.musicStartedAt);
  assert.equal((await audio()).musicStartCount, 1);
  record('返回主页不重播入场，两处设置同步且解除静音延续播放');
  const beforeInvalid = (await audio()).preferences;
  await home.evaluate(() => { parent.postMessage({ source: 'kongxiaozhu-home', type: 'audio-settings', patch: { musicVolume: 9 } }, '*'); parent.postMessage({ source: 'kongxiaozhu-home', type: 'audio-settings', patch: { arbitrary: true } }, '*'); });
  await page.waitForTimeout(150);
  assert.deepEqual((await audio()).preferences, beforeInvalid);
  record('越界音量与未知偏好字段被拒绝');
  // Persist the off state, and reduced motion, then check a real fresh process.
  await home.locator('[data-audio-toggle="enabled"]').click();
  if (!(await homeState()).prefs.reduced) await home.locator('[data-action="motion"]').click();
  await close();
  await launch();
  await completeIntro();
  assert.equal((await homeState()).intro.completed, true);
  await page.waitForFunction(() => window.__kxAudio);
  const restored = await audio();
  assert.equal(restored.preferences.enabled, false); assert.equal(restored.preferences.typing, false); assert.equal(restored.preferences.musicVolume, 0.17);
  assert.equal(restored.contextState, 'not-created'); assert.equal(restored.outputRms, 0);
  record('重启保持关闭与音量偏好；减少动态直接完成入场且不偷偷播放', restored);
  await home.locator('[data-action="settings"]').click();
  await home.locator('[data-action="motion"]').click();
  await close();
  await launch();
  await page.getByTestId('skip-welcome').click();
  await home.waitForFunction(() => window.__kxHome.getState().intro.active);
  const skipStart = Date.now();
  await home.getByRole('button', { name: '跳过入场动画', exact: true }).click();
  await completeIntro();
  assert.ok(Date.now() - skipStart < 4000);
  await home.locator('[data-action="search"]').click();
  await home.getByRole('dialog', { name: '实验索引', exact: true }).waitFor();
  record('跳过入场立即恢复可操作的四实验索引');
  assert.deepEqual(rendererErrors, []); assert.deepEqual(externalRequests, []); assert.deepEqual(oldModels, []);
  record('无渲染异常、外网资源或旧 GLB 请求');
  report.passed = true;
} catch (error) {
  report.passed = false; report.errors.push(error.stack || String(error)); console.error(error);
  if (app && page && !page.isClosed()) await captureElectron(app, `evidence/screenshots/audio-${label}-failure.png`).catch(() => {});
  process.exitCode = 1;
} finally {
  if (app) await close().catch(() => {});
  report.rendererErrors = rendererErrors; report.finishedAt = new Date().toISOString();
  await fs.mkdir('evidence', { recursive: true });
  await fs.writeFile(`evidence/audio-intro-${label}.json`, JSON.stringify(report, null, 2) + '\n');
}
