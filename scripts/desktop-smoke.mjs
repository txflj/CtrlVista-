import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { CASES, createCaseConfig } from '../src/core/index.mjs';

const require = createRequire(import.meta.url);
const playwrightPath = process.env.KX_PLAYWRIGHT_PATH || 'playwright';
const { _electron } = require(playwrightPath);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packaged = process.argv.includes('--packaged');
const version = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8')).version;
const executablePath = packaged ? path.join(root, 'release', `控小助-${version}-win32-x64`, '控小助.exe') : path.join(root, 'node_modules/electron/dist/electron.exe');
const dataDir = path.join(root, '.test-data', `${packaged ? 'packaged' : 'desktop'}-${Date.now()}`);
await fs.mkdir(dataDir, { recursive: true });
const evidenceDir = path.join(root, 'evidence');
await fs.mkdir(path.join(evidenceDir, 'screenshots'), { recursive: true });
const report = { startedAt: new Date().toISOString(), packaged, executablePath, dataDir, checks: [], errors: [], scope: '本机 Electron 与本机 HTTP 模拟服务验证，无真实 DeepSeek 请求。' };
const record = (name, detail = true) => { report.checks.push({ name, detail }); console.log(`PASS ${name}`); };
const env = { ...process.env, KX_TEST_MODE: '1', KX_TEST_SHOW: '1', KX_TEST_DATA_DIR: dataDir };
delete env.ELECTRON_RUN_AS_NODE;
if (packaged) env.PATH = `${process.env.SystemRoot}\\System32;${process.env.SystemRoot}`;
let app, server, page;
const rendererErrors = [];
async function openLibraryFromHome() {
  await page.getByTestId('homepage-frame').waitFor({ state: 'visible', timeout: 30000 });
  const home = page.frameLocator('[data-testid="homepage-frame"]');
  await home.locator('[data-action="search"]').click();
  await home.getByRole('dialog', { name: '实验索引', exact: true }).waitFor();
  await home.locator('[data-action="library"]').click();
  await page.getByTestId('start-motor').waitFor();
}
try {
  app = await _electron.launch({ executablePath, args: packaged ? [] : [root], env, timeout: 30000 });
  page = await app.firstWindow();
  page.on('pageerror', error => rendererErrors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await openLibraryFromHome();
  record('桌面窗口加载');
  const boot = await page.evaluate(() => window.kongxiaozhu.getBootstrap());
  assert.equal(boot.settings.provider, 'deepseek');
  assert.equal(boot.settings.hasKey, false);
  assert.equal(boot.experiments.length, 0);
  assert.equal(path.resolve(boot.dataPath), dataDir);
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  record('独立测试数据目录与受限桌面桥');

  const runs = [];
  for (const definition of CASES) {
    const config = createCaseConfig(definition.id);
    config.controller = definition.referenceController;
    const run = await page.evaluate(config => window.kongxiaozhu.simulate(config, { configVersion: 1 }), config);
    assert.equal(run.status, 'completed'); assert.equal(run.verdict, 'pass');
    runs.push(run);
    record(`${definition.name}：桌面计算线程达标`, run.metrics);
  }
  const first = runs[0];
  const now = new Date().toISOString();
  let experiment = { id: randomUUID(), schemaVersion: 1, version: 1, caseId: 'motor', title: '桌面集成测试电机实验', mode: 'guided', config: first.config, runs: [first], candidates: [], aiSessions: [], predictions: [], notes: '测试记录', reflection: '指标可复现', createdAt: now, updatedAt: now, activeRunId: first.id };
  experiment = await page.evaluate(e => window.kongxiaozhu.saveExperiment(e), experiment);
  const tune = await page.evaluate(config => window.kongxiaozhu.autotune(config, { budget: 48, seed: 42, configVersion: 1 }), first.config);
  assert.equal(tune.evaluated, 48); assert.ok(tune.candidates.some(c => c.run.verdict === 'pass'));
  record('桌面整定与后台线程');
  const reproduction = await page.evaluate(run => window.kongxiaozhu.reproduceRun(run), first);
  assert.equal(reproduction.comparison.pass, true);
  record('桌面计算复现', reproduction.comparison);

  for (const format of ['json', 'csv', 'html']) {
    const outputFile = path.join(dataDir, `export.${format}`);
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, outputFile);
    const result = await page.evaluate(({ e, format }) => window.kongxiaozhu.exportExperiment(e, format), { e: experiment, format });
    assert.equal(result.path, outputFile); assert.ok((await fs.stat(outputFile)).size > 100);
  }
  const exportFile = path.join(dataDir, 'export.json');
  await app.evaluate(({ dialog }, filePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] }); }, exportFile);
  const imported = await page.evaluate(() => window.kongxiaozhu.importExperiment());
  assert.notEqual(imported.experiment.id, experiment.id);
  assert.deepEqual(imported.experiment.runs[0].curves, first.curves);
  record('JSON／CSV／HTML 导出与 JSON 重新导入');

  const requests = [];
  server = http.createServer(async (req, res) => {
    let body = ''; for await (const chunk of req) body += chunk;
    const request = JSON.parse(body); requests.push(request);
    const tools = request.tools || [];
    let message;
    if (!tools.length) message = { role: 'assistant', content: 'OK' };
    else if (tools[0].function.name === 'propose_configuration') message = { role: 'assistant', content: null, tool_calls: [{ id: 'goal1', type: 'function', function: { name: 'propose_configuration', arguments: JSON.stringify({ patch: { goals: { overshootMax: 8 } }, missing: [], explanation: '按用户输入生成目标提案。' }) } }] };
    else if (request.messages.some(m => m.role === 'tool')) message = { role: 'assistant', content: '本机协议测试：候选已实际仿真，请以工具结果中的指标判断。' };
    else message = { role: 'assistant', content: null, tool_calls: [{ id: 'candidate1', type: 'function', function: { name: 'validate_candidate', arguments: JSON.stringify({ hypothesis: '验证案例参考 PI 参数。', controller: CASES[0].referenceController }) } }] };
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ choices: [{ finish_reason: message.tool_calls ? 'tool_calls' : 'stop', message }] }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const apiSettings = { provider: 'deepseek', baseUrl: `http://127.0.0.1:${server.address().port}`, model: 'local-protocol-test', timeoutMs: 5000, apiKey: 'not-a-real-api-key-local-test' };
  const settings = await page.evaluate(s => window.kongxiaozhu.saveSettings(s), apiSettings);
  assert.equal(settings.hasKey, true); assert.equal(settings.apiKey, undefined);
  const savedSettings = await fs.readFile(path.join(dataDir, 'settings.json'), 'utf8');
  assert.ok(!savedSettings.includes(apiSettings.apiKey));
  assert.equal((await page.evaluate(() => window.kongxiaozhu.testConnection())).ok, true);
  const session = await page.evaluate(e => window.kongxiaozhu.requestAi({ experimentId: e.id, configVersion: e.version, config: e.config, question: '验证降低稳态误差的参数。' }), experiment);
  assert.equal(session.candidates.length, 1); assert.equal(session.candidates[0].run.verdict, 'pass');
  assert.equal(session.toolLog[0].status, 'completed');
  assert.ok(requests.some(r => r.messages.some(m => m.role === 'tool')));
  assert.ok(requests.every(r => r.thinking?.type === 'disabled'));
  const proposal = await page.evaluate(config => window.kongxiaozhu.interpretGoal({ text: '超调上限设为 8%', config }), first.config);
  assert.equal(proposal.patch.goals.overshootMax, 8);
  experiment.aiSessions.push(session);
  experiment.candidates.push(...session.candidates.map(c => ({ ...c, source: 'ai', label: 'AI 候选 1', basedOnVersion: 1 })));
  experiment = await page.evaluate(e => window.kongxiaozhu.saveExperiment(e), experiment);
  record('Windows 密钥加密与实际工具调用闭环（本机模拟服务）');
  await page.evaluate(() => window.kongxiaozhu.saveSettings({ provider: 'deepseek', baseUrl: 'https://api.deepseek.com', model: 'deepseek-flash', timeoutMs: 60000, clearKey: true }));
  assert.equal((await page.evaluate(() => window.kongxiaozhu.getSettings())).hasKey, false);

  await page.reload();
  await openLibraryFromHome();
  await page.getByTestId('start-motor').waitFor();
  await page.screenshot({ path: path.join(evidenceDir, 'screenshots', `${packaged ? 'packaged' : 'desktop'}-library.png`), fullPage: true });
  await page.getByTestId('open-settings').click();
  await page.getByRole('heading', { name: '模型与本机设置' }).waitFor();
  assert.ok(await page.getByLabel('服务地址', { exact: true }).inputValue());
  await page.screenshot({ path: path.join(evidenceDir, 'screenshots', `${packaged ? 'packaged' : 'desktop'}-settings.png`), fullPage: true });
  record('设置界面与 DeepSeek 预设');
  await page.getByLabel('服务地址', { exact: true }).fill(apiSettings.baseUrl);
  await page.getByLabel('模型名称', { exact: true }).fill(apiSettings.model);
  await page.getByLabel(/^API 密钥/).fill(apiSettings.apiKey);
  await page.getByRole('button', { name: '保存并测试连接', exact: true }).click();
  await page.getByText('模型服务连接成功。此检查不等同于完成控制实验工具调用验证。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭对话框' }).click();
  await page.getByTestId('start-motor').click();
  await page.getByLabel('自动运行', { exact: true }).uncheck();
  await page.getByTestId('run-simulation').click();
  await page.getByText('计算完成', { exact: true }).first().waitFor();
  await page.getByLabel('比例 Kp', { exact: true }).fill('2');
  await page.getByLabel('比例 Kp', { exact: true }).press('Tab');
  await page.getByLabel('积分 Ki', { exact: true }).fill('4');
  await page.getByLabel('积分 Ki', { exact: true }).press('Tab');
  await page.getByTestId('run-simulation').click();
  await page.getByText('全部必需条件在声明的计算和观察条件下通过', { exact: true }).first().waitFor();
  const bluePath = page.locator('.response-chart path[data-series-index="0"]');
  const purplePath = page.locator('.response-chart path[data-series-index="1"]');
  const pinnedId = await purplePath.getAttribute('data-run-id');
  const beforeRepeat = await bluePath.getAttribute('data-run-id');
  await page.getByTestId('run-simulation').click();
  await page.waitForFunction(previous => document.querySelector('.response-chart path[data-series-index="0"]')?.getAttribute('data-run-id') !== previous, beforeRepeat);
  assert.equal(await purplePath.getAttribute('data-run-id'), pinnedId);
  const lastManualId = await bluePath.getAttribute('data-run-id');
  await page.getByLabel('自动运行', { exact: true }).check();
  await page.getByLabel('比例 Kp', { exact: true }).fill('3');
  await page.getByLabel('比例 Kp', { exact: true }).press('Tab');
  await page.waitForFunction(previous => document.querySelector('.response-chart path[data-series-index="0"]')?.getAttribute('data-run-id') !== previous, lastManualId);
  assert.equal(await purplePath.getAttribute('data-run-id'), pinnedId);
  await page.getByTestId('run-simulation').click();
  await page.waitForFunction(previous => document.querySelector('.response-chart path[data-series-index="1"]')?.getAttribute('data-run-id') === previous, lastManualId);
  await page.getByLabel('自动运行', { exact: true }).uncheck();
  record('固定对照在重复运行和自动预览中保持，手动新方案才推进');
  await page.getByTestId('workspace-tab-learning').click();
  await page.getByLabel('操作前，我预计会发生什么', { exact: true }).fill('增大积分后稳态误差应减小。');
  await page.getByRole('button', { name: '保存预测', exact: true }).click();
  await page.getByLabel('实验后的观察', { exact: true }).fill('本次计算全部指标达标。');
  await page.getByLabel('实验笔记', { exact: true }).fill('UI 流程已实际运行。');
  await page.getByTestId('workspace-tab-comparison').click();
  await page.getByRole('button', { name: '生成自动整定对照', exact: true }).click();
  await page.locator('.candidate').first().waitFor();
  await page.getByLabel('加入比较', { exact: true }).first().check();
  await page.locator('.comparison-table').waitFor();
  await page.getByRole('button', { name: '重新验证并应用', exact: true }).first().click();
  await page.getByText('候选已按当前条件重新验证并应用，历史方案保持不变。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '切换自由探索', exact: true }).click();
  await page.getByRole('button', { name: '切换引导实验', exact: true }).waitFor();
  const firstUiTitle = await page.getByLabel('实验名称', { exact: true }).inputValue();
  await page.getByTestId('workspace-tab-history').click();
  await page.getByRole('button', { name: '立即保存', exact: true }).click();
  await page.getByTestId('nav-library').click();
  await page.getByRole('button', { name: '继续当前实验', exact: true }).click();
  assert.equal(await page.getByLabel('实验名称', { exact: true }).inputValue(), firstUiTitle);
  record('界面创建实验、调参、预测观察、整定比较、应用和切换页面保留状态');
  await page.getByRole('button', { name: 'AI 助手', exact: true }).click();
  await page.getByRole('button', { name: '提出并验证建议', exact: true }).click();
  await page.getByText('本机协议测试：候选已实际仿真，请以工具结果中的指标判断。', { exact: true }).waitFor();
  await page.getByText('用自然语言提出模型或目标设置', { exact: true }).click();
  await page.getByLabel('你想设置什么', { exact: true }).fill('超调上限设为 8%。');
  await page.getByRole('button', { name: '解析为配置提案', exact: true }).click();
  await page.getByRole('button', { name: '确认这些设置并应用', exact: true }).click();
  await page.getByRole('button', { name: '前往方案对比', exact: true }).click();
  await page.getByRole('button', { name: '重新验证并应用', exact: true }).first().click();
  await page.getByText('候选已按当前条件重新验证并应用，历史方案保持不变。', { exact: true }).waitFor();
  record('界面 AI 实算候选、自然语言提案确认和旧候选重新验证（本机模拟服务）');
  await page.evaluate(() => { window.scrollTo(0, 0); document.querySelector('.module-content').scrollTop = 0; });
  await page.getByTestId('run-simulation').scrollIntoViewIfNeeded();
  if (await page.getByRole('button', { name: '关闭提示', exact: true }).count()) await page.getByRole('button', { name: '关闭提示', exact: true }).click();
  await page.screenshot({ path: path.join(evidenceDir, 'screenshots', `${packaged ? 'packaged' : 'desktop'}-workbench.png`) });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1040, 720));
  await page.waitForFunction(() => window.innerWidth <= 1040);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true);
  record('最小桌面窗口宽度无页面横向溢出');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 960));
  await page.getByTestId('workspace-tab-history').click();
  await page.getByRole('button', { name: '复算核对', exact: true }).first().click();
  await page.getByText('复算一致', { exact: true }).waitFor();
  const uiExportFile = path.join(dataDir, 'ui-export.json');
  await app.evaluate(({ dialog }, filePath) => {
    dialog.showSaveDialog = async () => ({ canceled: false, filePath });
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] });
  }, uiExportFile);
  await page.getByRole('button', { name: '导出实验包', exact: true }).click();
  await page.getByText(/已导出：/).waitFor();
  await page.getByTestId('nav-records').click();
  await page.getByRole('button', { name: '导入实验包', exact: true }).click();
  await page.getByText('实验包已作为新实验导入。可选择历史运行进行复算核对。', { exact: true }).waitFor();
  record('界面复算、导出、导入恢复');
  await page.getByTestId('workspace-tab-learning').click();
  await page.getByLabel('实验笔记', { exact: true }).fill('关闭窗口前最后的输入应该被保存。');
  assert.deepEqual(rendererErrors, []);
  record('渲染器无未处理异常');
  await app.close(); app = null;
  app = await _electron.launch({ executablePath, args: packaged ? [] : [root], env, timeout: 30000 });
  page = await app.firstWindow();
  await openLibraryFromHome();
  const restored = await page.evaluate(() => window.kongxiaozhu.listExperiments());
  assert.ok(restored.length >= 4);
  assert.ok(restored.find(e => e.id === experiment.id).aiSessions.length === 1);
  assert.ok(restored.some(e => e.notes === '关闭窗口前最后的输入应该被保存。'));
  record('退出后重新打开，实验与 AI 证据仍在');
  report.passed = true;
} catch (error) {
  report.passed = false; report.errors.push(error.stack); console.error(error);
  if (page && !page.isClosed()) await page.screenshot({ path: path.join(evidenceDir, 'screenshots', 'smoke-failure.png'), fullPage: true }).catch(() => {});
  process.exitCode = 1;
} finally {
  if (app) await app.close().catch(() => {});
  if (server) await new Promise(resolve => server.close(resolve));
  report.finishedAt = new Date().toISOString();
  await fs.writeFile(path.join(evidenceDir, packaged ? 'packaged-smoke.json' : 'desktop-smoke.json'), JSON.stringify(report, null, 2));
}
